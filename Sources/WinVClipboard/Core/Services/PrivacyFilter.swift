import Foundation
import AppKit

public final class PrivacyFilter: @unchecked Sendable {
    public static let shared = PrivacyFilter()

    public static let concealedPasteboardTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("com.apple.findmy.clipboard"),
        NSPasteboard.PasteboardType("PasswordPboardType")
    ]

    public static let defaultExcludedBundleIdentifiers: Set<String> = [
        "com.1password.1password",
        "com.1password.1password-native-helper",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephone",
        "com.dashlane.Dashlane",
        "in.sinew.Enpass-Desktop",
        "com.nordpass.macos"
    ]

    private let userDefaultsKey = "WinVExcludedBundleIDs"
    private let pausedDefaultsKey = "WinVClipboardMonitoringPaused"
    private let lock = NSLock()

    private var customExcludedBundleIDs: Set<String> = []

    public init() {
        loadCustomExclusions()
    }

    public var isMonitoringPaused: Bool {
        get {
            UserDefaults.standard.bool(forKey: pausedDefaultsKey)
        }
        set {
            UserDefaults.standard.set(newValue, forKey: pausedDefaultsKey)
        }
    }

    public func loadCustomExclusions() {
        lock.lock()
        defer { lock.unlock() }
        let saved = UserDefaults.standard.stringArray(forKey: userDefaultsKey) ?? []
        customExcludedBundleIDs = Set(saved)
    }

    public func allExcludedBundleIDs() -> Set<String> {
        lock.lock()
        defer { lock.unlock() }
        return PrivacyFilter.defaultExcludedBundleIdentifiers.union(customExcludedBundleIDs)
    }

    public func addExcludedBundleID(_ bundleID: String) {
        lock.lock()
        defer { lock.unlock() }
        customExcludedBundleIDs.insert(bundleID)
        UserDefaults.standard.set(Array(customExcludedBundleIDs), forKey: userDefaultsKey)
    }

    public func removeExcludedBundleID(_ bundleID: String) {
        lock.lock()
        defer { lock.unlock() }
        customExcludedBundleIDs.remove(bundleID)
        UserDefaults.standard.set(Array(customExcludedBundleIDs), forKey: userDefaultsKey)
    }

    /// Determines if a pasteboard contains sensitive data that should NOT be recorded.
    public func shouldIgnore(pasteboard: NSPasteboard, sourceBundleID: String?) -> Bool {
        if isMonitoringPaused {
            return true
        }

        // 1. Check for Concealed or Password types
        if let types = pasteboard.types {
            for type in types {
                for concealed in PrivacyFilter.concealedPasteboardTypes {
                    if type == concealed || type.rawValue.contains("ConcealedType") || type.rawValue.contains("Password") {
                        return true
                    }
                }
            }
        }

        // 2. Check source application bundle ID
        if let bundleID = sourceBundleID {
            let excluded = allExcludedBundleIDs()
            for id in excluded {
                if bundleID.caseInsensitiveCompare(id) == .orderedSame || bundleID.hasPrefix(id) {
                    return true
                }
            }
        }

        return false
    }
}
